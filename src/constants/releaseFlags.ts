/**
 * リリース単位で機能の露出を切り替えるフラグ。
 *
 * ── PREMIUM_UI_ENABLED ──────────────────────────────────
 * false の間は、課金に関する導線を一切出さない:
 *   - 設定画面の「プレミアム」行を表示しない
 *   - カレンダーの無料範囲制限（直近3ヶ月）を適用しない ＝ 全期間を閲覧できる
 *   - 上記の結果、ペイウォール画面へ到達する導線が無くなる
 *     （app/paywall.tsx と PaywallCompareTable.tsx は消さずに残してある）
 *
 * 【なぜ初回リリースで隠すのか ★変更前に読むこと】
 * ペイウォールの「プレミアムに加入する」はストア決済未接続のスタブで、押しても
 * 「準備中です」と出るだけ。App Store Review Guideline 2.1（App Completeness）は
 * 機能しないボタンやプレースホルダを不備として扱うため、リジェクトの典型例にあたる。
 * PROJECT_STATE.md 2章の「ペイウォールが動くまでユーザー数を増やす施策をしない」
 * という方針とも整合する。
 *
 * IAPを実装したら true に戻すだけでよい。UIは残してあるのでそのまま復活する。
 *
 * データ面の安全性: 履歴は課金状況に関わらず全期間が端末内に保存されている
 * （要件書9章。無料の3ヶ月はあくまでUI上の閲覧制限）。
 * よって制限を外しても、あとで戻しても、データの欠落や不整合は起きない。
 */
export const PREMIUM_UI_ENABLED = false;

/**
 * ── SCREEN_TIME_UI_ENABLED ──────────────────────────────
 * false の間は、スクリーンタイム連携の導線を一切出さない:
 *   - 設定画面の「スクリーンタイム連携」セクションを表示しない
 *   - 結果として自己申告の入力手段が無くなる
 *     （ScreenTimeInput.tsx・services/screenTime・screenTimeLogRepo.ts は消さずに残してある）
 *
 * 【なぜ隠すのか】OSから自動取得せず手入力させる作りで、初回リリースでは
 * 手間に見合う価値を出せていないと判断したため。軸スコアの計算にも使っていない。
 *
 * 【消さずに隠す理由 ★変更前に読むこと】
 * screen_time_log テーブルは schema.ts の v1 で作られている。コードごと消すなら
 * マイグレーションの追加が必要だが、このプロジェクトでは過去に user_version だけが
 * 進んで todo テーブルが作られない事故が起きている（schema.ts のコメント参照）。
 * 申請直前にそのリスクを取る理由がないので、UIの露出だけを止めている。
 *
 * 【戻すときに忘れないこと】
 * true に戻す際は、legalDocuments.ts にスクリーンタイムの説明を書き戻すこと。
 * 隠すのに合わせて、プライバシーポリシーと利用規約から記述を削除してある。
 */
export const SCREEN_TIME_UI_ENABLED = false;
